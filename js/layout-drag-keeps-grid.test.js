function clone(o) { return JSON.parse(JSON.stringify(o)); }
function wait(ms) { return new Promise(function (r) { setTimeout(r, ms); }); }

/* The store hands out the test's owner profile; saves go through the real path. */
function ownStore(env, p) {
  var store = env.win.CognationTowerProfileStore;
  var state = clone(p);
  var realSave = store.save;
  store.get = function () { return clone(state); };
  store.save = function (d, o) { state = clone(d); return realSave.call(store, d, o); };
  return { current: function () { return clone(state); } };
}

async function render(env, p) {
  var sync = env.win.CognationTowerLayoutSync;
  sync.apply(p);
  await wait(5);
  sync.apply(p);
  var dom = buildRoot();
  /* Same order as the page: bind the stickers, then lay out. */
  env.win.__dragHook.initScrapbookStickers(dom.root);
  env.win.__dragHook.spawnUnplacedWidgets(dom.root, p);
  return dom;
}

function drag(env, dom, id, dx, dy) {
  var el = dom.stage.querySelector('[data-tower-widget="' + id + '"]');
  var r = el.getBoundingClientRect();
  var x0 = r.left + r.width / 2, y0 = r.top + 20;
  var ev = function (x, y) { return { target: el, clientX: x, clientY: y, pointerId: 1, cancelable: true, button: 0, preventDefault: function () {}, stopPropagation: function () {} }; };
  dom.stage.dispatch("pointerdown", ev(x0, y0));
  for (var i = 1; i <= 10; i++) env.doc.dispatchEvent(Object.assign(ev(x0 + dx * i / 10, y0 + dy * i / 10), { type: "pointermove" }));
  env.doc.dispatchEvent(Object.assign(ev(x0 + dx, y0 + dy), { type: "pointerup" }));
}

function layoutWrites(env) { return env.writes.filter(function (w) { return w.table === "tower_widget_layouts"; }); }

test("a drag with no saved layout saves exactly what's on screen", async function () {
  /* Open: fresh owner, no layout row -> default grid. */
  var env = boot(null);
  var p = profile();
  ownStore(env, p);
  var dom = await render(env, p);
  assert.ok(dom.stage.classList.contains("is-default-grid"), "fresh Tower opens on the default grid");
  var open = rects(dom.stage);

  /* Drag the avatar +40/+30 and let go. */
  drag(env, dom, "avatar", 40, 30);
  var afterDrag = rects(dom.stage);
  await wait(700); /* past the 600ms upload debounce */
  var w = layoutWrites(env);
  assert.strictEqual(w.length, 1, "one layout write for one drag end");
  var savedRow = w[0].body.layout;

  /* On screen right after the drop: the profile card moved by the drag, nothing else changed. */
  assert.deepStrictEqual(afterDrag.avatar, [open.avatar[0] + 40, open.avatar[1] + 30, open.avatar[2], open.avatar[3]], "dragged widget: x/y move by the drag, size kept");
  assert.deepStrictEqual(afterDrag.identity, [open.identity[0] + 40, open.identity[1] + 30, open.identity[2], open.identity[3]], "the name rides with its profile card");
  ["music", "polaroid", "instax"].forEach(function (id) {
    assert.deepStrictEqual(afterDrag[id], open[id], id + " did not move or resize on drag");
  });

  /* Reload from the row that drag end uploaded. */
  var env2 = boot(savedRow);
  var p2 = profile();
  ownStore(env2, p2);
  var dom2 = await render(env2, p2);
  var reload = rects(dom2.stage);
  assert.deepStrictEqual(reload, afterDrag, "reload paints exactly what was on screen after the drop");
  ["music", "polaroid", "instax"].forEach(function (id) {
    assert.deepStrictEqual(reload[id], open[id], id + ": 0px from the open grid after reload");
  });
  await wait(700);
  assert.strictEqual(layoutWrites(env2).length, 0, "reload writes nothing");
});

