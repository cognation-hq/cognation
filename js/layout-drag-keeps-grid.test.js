/**
 * A drag with no saved layout saves exactly what's on screen
 * (Designer spec, layout-drag-keeps-grid).
 *
 * Fresh owner, no tower_widget_layouts row: the Tower shows the default grid.
 * The owner drags the avatar +40/+30 and lets go. Only the dragged widget's x/y
 * change; nothing else moves or resizes, and the reload (served from the row
 * that drag end uploaded) paints the same rects. Reset brings back the exact
 * default grid. A saved desktop nudge never reaches the phone stack.
 *
 * The real drag handler, render and save path run against a tiny fake DOM.
 * The fake lays out the default grid with fixed slots (from the 1280 shot) and
 * free stickers from --sticker-x/y/w with each sticker's own size, the way the
 * CSS does. Stubbed session and client only; nothing leaves the process.
 * Run: node --test js/layout-drag-keeps-grid.test.js
 */
